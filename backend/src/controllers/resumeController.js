const { v4: uuidv4 } = require('uuid');
const { supabase } = require('../config/supabase');
const { scoreResume } = require('../services/atsService');
const logger = require('../config/logger');

const DEFAULT_CONTENT = {
  contact: { name: '', title: '', email: '', phone: '', location: '', linkedin: '', github: '', website: '' },
  summary: '', experience: [], education: [], skills: [], certifications: [], projects: [], languages: [], awards: [], customSections: [],
};
const DEFAULT_DESIGN = { primaryColor: '#2563EB', fontFamily: 'Inter, sans-serif', fontSize: 11 };
const DEFAULT_ORDER = ['contact', 'summary', 'experience', 'education', 'skills'];

function mapResume(r) {
  if (!r) return null;
  return {
    ...r,
    sectionOrder: r.section_order || [],
    atsFeedback: r.ats_feedback || [],
    isPublic: Boolean(r.is_public),
  };
}

async function saveVersion(resumeId, snapshot, label) {
  const { data: lastVer, error: readError } = await supabase
    .from('resume_versions')
    .select('version_num')
    .eq('resume_id', resumeId)
    .order('version_num', { ascending: false })
    .limit(1)
    .maybeSingle();

  if (readError) throw readError;
  const nextNum = lastVer ? lastVer.version_num + 1 : 1;
  const { error } = await supabase
    .from('resume_versions')
    .insert({ id: uuidv4(), resume_id: resumeId, version_num: nextNum, snapshot, label: label || null });

  if (error) throw error;
}

function versionSnapshot(resume) {
  return {
    _snapshotVersion: 1,
    content: resume.content,
    title: resume.title,
    template_id: resume.template_id,
    design: resume.design,
    section_order: resume.section_order,
  };
}

async function createResume(req, res) {
  const { title, templateId, content, design, sectionOrder } = req.body;

  // No hardcoded default template id anymore (ids are now UUIDs generated by Postgres).
  // If none is supplied the resume is created without one; the user picks a template
  // in the design sidebar, matching the existing "proceed with null" fallback behaviour.
  if (templateId) {
    const { data: tmpl, error: tmplError } = await supabase
      .from('resume_templates')
      .select('id')
      .eq('id', templateId)
      .maybeSingle();
    if (tmplError || !tmpl) {
      return res.status(404).json({ success: false, message: 'Template not found' });
    }
  }

  const id = req.body.id || uuidv4();
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(id)) {
    return res.status(400).json({ success: false, message: 'Invalid resume id' });
  }
  const { data: resume, error } = await supabase
    .from('resumes')
    .insert({
      id,
      user_id: req.user.id,
      template_id: templateId || null,
      title: title || 'Untitled Resume',
      content: content || DEFAULT_CONTENT,
      design: design || DEFAULT_DESIGN,
      section_order: sectionOrder || DEFAULT_ORDER,
    })
    .select('*')
    .single();

  if (error) {
    // A retried local draft retains its id, so a lost response cannot create
    // another resume. updateResume separately checks the owner's identity.
    if (error.code === '23505' && req.body.id) {
      return updateResume({ ...req, params: { ...req.params, id } }, res);
    }
    logger.error(`createResume failed: ${error.message}`);
    return res.status(500).json({ success: false, message: 'Failed to create resume' });
  }

  return res.status(201).json({ success: true, resume: mapResume(resume) });
}

async function listResumes(req, res) {
  const { data: resumes, error } = await supabase
    .from('resumes')
    .select('*')
    .eq('user_id', req.user.id)
    .order('updated_at', { ascending: false });

  if (error) {
    logger.error(`listResumes failed: ${error.message}`);
    return res.status(500).json({ success: false, message: 'Failed to load resumes' });
  }

  // Fetch template names in one extra query rather than relying on supabase-js's
  // embedded-resource join syntax (avoids depending on a specific FK constraint name).
  const templateIds = [...new Set((resumes || []).map((r) => r.template_id).filter(Boolean))];
  let templateNameById = {};
  if (templateIds.length > 0) {
    const { data: templates } = await supabase
      .from('resume_templates')
      .select('id, name')
      .in('id', templateIds);
    templateNameById = (templates || []).reduce((acc, t) => ({ ...acc, [t.id]: t.name }), {});
  }

  const withTemplateName = (resumes || []).map((r) => ({
    ...r,
    template_name: r.template_id ? templateNameById[r.template_id] || null : null,
  }));

  return res.json({ success: true, resumes: withTemplateName.map(mapResume) });
}

async function getResume(req, res) {
  const { data: resume, error } = await supabase
    .from('resumes')
    .select('*')
    .eq('id', req.params.id)
    .or(`user_id.eq.${req.user.id},is_public.eq.true`)
    .maybeSingle();

  if (error || !resume) return res.status(404).json({ success: false, message: 'Resume not found' });

  let templateFields = {};
  if (resume.template_id) {
    const { data: tmpl } = await supabase
      .from('resume_templates')
      .select('html_content, css_content')
      .eq('id', resume.template_id)
      .maybeSingle();
    if (tmpl) templateFields = { html_content: tmpl.html_content, css_content: tmpl.css_content };
  }

  return res.json({ success: true, resume: mapResume({ ...resume, ...templateFields }) });
}

async function updateResume(req, res) {
  const { data: existing, error: fetchError } = await supabase
    .from('resumes')
    .select('*')
    .eq('id', req.params.id)
    .eq('user_id', req.user.id)
    .maybeSingle();

  if (fetchError || !existing) return res.status(404).json({ success: false, message: 'Resume not found' });

  const { title, templateId, content, design, sectionOrder, isPublic } = req.body;

  const updates = { updated_at: new Date().toISOString() };
  if (title !== undefined) updates.title = title;
  if (templateId !== undefined) updates.template_id = templateId;
  if (content !== undefined) updates.content = content;
  if (design !== undefined) updates.design = design;
  if (sectionOrder !== undefined) updates.section_order = sectionOrder;
  if (isPublic !== undefined) updates.is_public = Boolean(isPublic);

  // Preserve the last saved state before changing it. If history cannot be
  // written, keep the resume intact and let the client retry the save.
  const changed = ['title', 'template_id', 'content', 'design', 'section_order']
    .some(key => key in updates && JSON.stringify(updates[key]) !== JSON.stringify(existing[key]));
  if (changed) {
    try {
      await saveVersion(existing.id, versionSnapshot(existing));
    } catch (err) {
      logger.error(`Failed to preserve resume history: ${err.message}`);
      return res.status(500).json({ success: false, message: 'Could not save version history. Please retry.' });
    }
  }

  const { data: updated, error } = await supabase
    .from('resumes')
    .update(updates)
    .eq('id', req.params.id)
    .eq('user_id', req.user.id)
    .select('*')
    .single();

  if (error) {
    logger.error(`updateResume failed for ${req.params.id}: ${error.message}`);
    return res.status(500).json({ success: false, message: 'Failed to update resume' });
  }

  return res.json({ success: true, resume: mapResume(updated) });
}

async function deleteResume(req, res) {
  const { data: deleted, error } = await supabase
    .from('resumes')
    .delete()
    .eq('id', req.params.id)
    .eq('user_id', req.user.id)
    .select('id');

  if (error) {
    logger.error(`deleteResume failed for ${req.params.id}: ${error.message}`);
    return res.status(500).json({ success: false, message: 'Failed to delete resume' });
  }
  if (!deleted || deleted.length === 0) return res.status(404).json({ success: false, message: 'Resume not found' });

  return res.json({ success: true, message: 'Resume deleted' });
}

async function getAtsScore(req, res) {
  const { data: resume, error } = await supabase
    .from('resumes')
    .select('*')
    .eq('id', req.params.id)
    .eq('user_id', req.user.id)
    .maybeSingle();

  if (error || !resume) return res.status(404).json({ success: false, message: 'Resume not found' });

  const result = await scoreResume(resume.content, resume.template_id);

  const { error: updateError } = await supabase
    .from('resumes')
    .update({ ats_score: result.score, ats_feedback: result.feedback, updated_at: new Date().toISOString() })
    .eq('id', resume.id);

  if (updateError) logger.error(`Failed to persist ATS score for ${resume.id}: ${updateError.message}`);

  return res.json({ success: true, ats: result });
}

async function duplicateResume(req, res) {
  const { data: original, error: fetchError } = await supabase
    .from('resumes')
    .select('*')
    .eq('id', req.params.id)
    .eq('user_id', req.user.id)
    .maybeSingle();

  if (fetchError || !original) return res.status(404).json({ success: false, message: 'Resume not found' });

  const id = uuidv4();
  const { data: duplicated, error } = await supabase
    .from('resumes')
    .insert({
      id,
      user_id: req.user.id,
      template_id: original.template_id,
      title: `${original.title} (Copy)`,
      content: original.content,
      design: original.design,
      section_order: original.section_order,
    })
    .select('*')
    .single();

  if (error) {
    logger.error(`duplicateResume failed for ${req.params.id}: ${error.message}`);
    return res.status(500).json({ success: false, message: 'Failed to duplicate resume' });
  }

  return res.status(201).json({ success: true, resume: mapResume(duplicated) });
}

async function getVersions(req, res) {
  const { data: owned, error: ownError } = await supabase
    .from('resumes')
    .select('id')
    .eq('id', req.params.id)
    .eq('user_id', req.user.id)
    .maybeSingle();
  if (ownError || !owned) return res.status(404).json({ success: false, message: 'Resume not found' });

  const { data: versions, error } = await supabase
    .from('resume_versions')
    .select('id, version_num, label, created_at')
    .eq('resume_id', req.params.id)
    .order('version_num', { ascending: false });

  if (error) {
    logger.error(`getVersions failed for ${req.params.id}: ${error.message}`);
    return res.status(500).json({ success: false, message: 'Failed to load versions' });
  }

  return res.json({ success: true, versions: versions || [] });
}

async function restoreVersion(req, res) {
  // Ownership check via the parent resume (resume_versions has no user_id column).
  const { data: owned, error: ownError } = await supabase
    .from('resumes')
    .select('id')
    .eq('id', req.params.id)
    .eq('user_id', req.user.id)
    .maybeSingle();
  if (ownError || !owned) return res.status(404).json({ success: false, message: 'Resume not found' });

  const { data: version, error } = await supabase
    .from('resume_versions')
    .select('*')
    .eq('id', req.params.versionId)
    .eq('resume_id', req.params.id)
    .maybeSingle();

  if (error || !version) return res.status(404).json({ success: false, message: 'Version not found' });

  const snapshot = version.snapshot || {};
  const body = snapshot._snapshotVersion === 1 ? {
    content: snapshot.content, title: snapshot.title,
    templateId: snapshot.template_id, design: snapshot.design,
    sectionOrder: snapshot.section_order,
  } : { content: snapshot }; // Older snapshots contain only content.
  return updateResume({ ...req, body }, res);
}

async function updateDesign(req, res) {
  return updateResume({ ...req, body: { design: req.body.design } }, res);
}

async function updateSectionOrder(req, res) {
  return updateResume({ ...req, body: { sectionOrder: req.body.sectionOrder } }, res);
}

module.exports = {
  createResume, listResumes, getResume, updateResume, deleteResume, getAtsScore,
  duplicateResume, getVersions, restoreVersion, updateDesign, updateSectionOrder,
};
